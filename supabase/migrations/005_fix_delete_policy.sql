-- 보관함 기록 삭제 시 RLS 권한 문제로 삭제가 안 되는 현상을 수정합니다.
-- Supabase SQL Editor에서 이 쿼리를 복사하여 실행해 주세요.
-- =====================================================================

-- 삭제 정책이 이미 있을 수 있으므로 먼저 삭제합니다 (에러 방지)
DROP POLICY IF EXISTS "visitors_delete_all" ON visitors;

-- 기존 정책을 대체할 확실한 삭제 허용 정책을 다시 만듭니다
CREATE POLICY "visitors_delete_all"
  ON visitors FOR DELETE
  USING (true);

